/**
 * Промпти AI-скілів реєстру.
 *
 * Правила авторингу нижче — не вигадка, а домовленості з ліда QA:
 * один кейс = одна перевірка; заголовок у стилі чек-листа, щоб за ним можна
 * було швидко пройти руками; перевірки — спостережувані на екрані твердження;
 * до кожної вимоги дописуємо те, чого в ній немає (негативні, нейтральні,
 * безпекові) і чесно позначаємо це як `derived`.
 *
 * Тримаємо промпти окремо від логіки, щоб їх можна було читати й правити
 * без ризику зламати обробку відповіді, і щоб тести могли перевірити,
 * що потрібне правило справді доїхало до моделі.
 */

/** Загальні правила авторингу кейсів — спільні для генератора й критика. */
export const CASE_AUTHORING_RULES = `ПРАВИЛА АВТОРИНГУ ТЕСТ-КЕЙСІВ (обов'язкові):
1. Один кейс = ОДНА перевірка. Якщо в голові «а ще заодно перевіримо…» — це окремий кейс.
2. Заголовок (title) — ємний, у стилі чек-листа, щоб інженер пройшов за ним вручну без уточнень.
   Формат: що робимо + що очікуємо. Наприклад: «Акт без суми — форма не зберігається, поле підсвічене».
   Заборонено: «Перевірка функціоналу», «Тест форми», «Позитивний сценарій».
3. checks[] — короткі перевірні твердження, СПОСТЕРЕЖУВАНІ на екрані: конкретний текст, стан кнопки,
   наявність рядка в таблиці, код відповіді, редирект. Кожне твердження атомарне — одне твердження = один рядок.
   Заборонено: «працює нормально», «коректно відображається», «все ок», «немає помилок», «функціонал справний».
4. preconditions — рівно те, що має бути правдою ДО початку: роль користувача, наявні дані, сторінка входу.
   Якщо нічого не потрібно — порожній рядок.
5. coverageKind:
   - 'quote' — перевірка прямо стоїть у тексті вимоги (можна показати пальцем на речення);
   - 'derived' — ми дописали те, чого у вимозі НЕМА.
6. Обов'язково додавай 'derived' кейси, яких не було у вимозі:
   - негативні: невалідні дані, неправильний формат, перевищення довжини, дубль;
   - нейтральні: порожні дані, межові значення (0, 1, максимум, максимум+1), скасування дії, оновлення сторінки;
   - безпекові: прямий URL без авторизації, доступ до об'єкта чужого користувача (підмінений id),
     дія не за своєю роллю, доступ після виходу/закінчення сесії.
7. rationale — ОДНЕ речення, чому цей кейс потрібен. Його читає інженер у черзі апрувів, тому
   формулюй по суті ризику, а не «щоб перевірити функціонал».
8. kind: 'positive' | 'negative' | 'neutral' | 'security' | 'a11y' | 'performance'.
   priority: 'P1' (гроші/доступ/блокує роботу) | 'P2' (основний потік) | 'P3' (другорядне) | 'P4' (косметика).
9. tags — 2-4 короткі мітки латиницею в kebab-case (наприклад: 'acts', 'validation', 'authz').
10. БЕЗПЕКА ДАНИХ: у формулюваннях заборонені руйнівні дії — реальна оплата/списання коштів,
    видалення акаунта, видалення чужих даних, масове видалення. Перевіряй такі місця
    лише до точки підтвердження (форма, попередження, права доступу).
11. Нічого не вигадуй про поля й кнопки, яких немає у вимозі: якщо назва невідома — описуй за роллю
    («кнопка збереження форми»), а не придумуй текст.`;

/** Системний промпт генератора кейсів. */
export function buildWriteCasesSystemPrompt(opts: {
  language: string;
  maxPerBlock: number;
  includeDerived: boolean;
}): string {
  return `Ти — senior QA-інженер, який пише тест-кейси за текстом вимог.
Твоя робота: з ОДНОГО блоку вимог зробити чек-лист кейсів, придатних до ручного проходу.

${CASE_AUTHORING_RULES}

ОБМЕЖЕННЯ ЦЬОГО ЗАПУСКУ:
- Не більше ${opts.maxPerBlock} кейсів. Якщо перевірок більше — залиш найцінніші за ризиком.
- ${
    opts.includeDerived
      ? "Обов'язково додай 'derived' кейси (негативні, нейтральні, безпекові) — щонайменше по одному з кожної групи, якщо блок це дозволяє."
      : "Тільки 'quote' кейси: нічого, чого немає прямо в тексті вимоги."
  }
- Мова всіх текстів (title, checks, preconditions, rationale): ${opts.language}. tags — латиниця.

ФОРМАТ ВІДПОВІДІ. Поверни ЛИШЕ валідний JSON, без пояснень і без markdown-огорожі:
{
  "cases": [
    {
      "coverageKind": "quote" | "derived",
      "rationale": "одне речення, чому кейс потрібен",
      "title": "ємний заголовок у стилі чек-листа",
      "kind": "positive" | "negative" | "neutral" | "security" | "a11y" | "performance",
      "priority": "P1" | "P2" | "P3" | "P4",
      "preconditions": "що має бути правдою до початку (може бути порожнім рядком)",
      "checks": ["атомарне спостережуване твердження", "…"],
      "tags": ["kebab-case"]
    }
  ]
}`;
}

/** Системний промпт критика: другий прохід над згенерованими кейсами. */
export function buildCriticSystemPrompt(opts: { language: string; maxPerBlock: number }): string {
  return `Ти — вимогливий рецензент тест-кейсів. Тобі дали блок вимоги і чернетки кейсів за ним.
Приведи чернетки до правил НЕ змінюючи їх задум.

${CASE_AUTHORING_RULES}

ЩО ЗРОБИТИ (саме в такому порядку):
1. Прибери тавтології: кейси, що перевіряють те саме іншими словами — лиши один, найконкретніший.
2. Прибери кейси БЕЗ перевірної умови: порожні checks або лише загальні слова
   («працює нормально», «коректно», «без помилок») і нічого спостережуваного.
3. Розбий складені перевірки: якщо в одному рядку checks два твердження («поле підсвічене ТА показано текст»),
   зроби два рядки. Якщо кейс перевіряє дві різні речі — розділи на два кейси.
4. Для кожного кейса з coverageKind='derived' переконайся, що rationale пояснює, ЧОМУ ми це дописали
   (який ризик закриваємо). Якщо пояснення загальне — перепиши його по суті ризику.
5. Виправ заголовки, за якими не можна пройти вручну: додай, що робимо і що очікуємо.
6. Прибери руйнівні дії (оплата, списання коштів, видалення акаунта чи чужих даних) з формулювань.
7. Не більше ${opts.maxPerBlock} кейсів на виході. Мова: ${opts.language}.

ФОРМАТ ВІДПОВІДІ. Поверни ЛИШЕ валідний JSON тієї ж форми, що й вхідні кейси, плюс перелік того, що ти прибрав:
{
  "cases": [ { "coverageKind": "...", "rationale": "...", "title": "...", "kind": "...", "priority": "...", "preconditions": "...", "checks": ["..."], "tags": ["..."] } ],
  "removed": ["короткий рядок: який кейс і чому прибрано"]
}`;
}

/** Юзер-промпт генератора: один блок вимог + контекст. Історії немає. */
export function buildWriteCasesUserPrompt(input: {
  projectName: string;
  sectionPath: string;
  block: { id: string; heading: string; text: string };
  examples?: Array<{ title: string; checks: string[] }>;
}): string {
  const payload: Record<string, unknown> = {
    проєкт: input.projectName,
    розділ: input.sectionPath,
    блок: {
      id: input.block.id,
      заголовок: input.block.heading,
      текст: input.block.text,
    },
  };
  if (input.examples && input.examples.length > 0) {
    // Few-shot зі справжніх кейсів команди — найсильніший спосіб задати стиль.
    payload['приклади_наших_кейсів'] = input.examples.slice(0, 5);
  }
  return `${JSON.stringify(payload, null, 2)}

Напиши кейси лише за цим блоком. Не вигадуй вимог з інших розділів.`;
}

/** Юзер-промпт критика: блок + чернетки. */
export function buildCriticUserPrompt(input: {
  sectionPath: string;
  block: { id: string; heading: string; text: string };
  drafts: unknown;
}): string {
  return `${JSON.stringify(
    {
      розділ: input.sectionPath,
      блок: { id: input.block.id, заголовок: input.block.heading, текст: input.block.text },
      чернетки: input.drafts,
    },
    null,
    2,
  )}

Поверни виправлений набір кейсів і список прибраного.`;
}

/** Системний промпт скіла перевірки покриття. */
export function buildValidateCoverageSystemPrompt(opts: { language: string }): string {
  return `Ти — QA-аудитор покриття. Тобі дають ОДИН блок вимоги і список наявних тест-кейсів.
Твоє завдання — знайти чотири речі й нічого більше.

1. gaps — що у ВИМОЗІ не покрито жодним кейсом. Для кожної прогалини:
   - "fragment": дослівний фрагмент тексту вимоги (одне-два речення, скопіюй з блоку, не перефразовуй);
   - "suggestion": готовий кейс, який закриває прогалину (за правилами авторингу нижче).
   Якщо блок покритий повністю — поверни порожній масив.
2. duplicates — кейси, що перевіряють те саме. "caseIds" — ДВА або більше id з наданого списку,
   "reason" — чим саме вони дублюються.
3. untestable — кейси без перевірної умови: порожні checks або лише загальні слова
   («працює нормально», «коректно», «без помилок»), нічого спостережуваного на екрані.
4. contradictions — кейс суперечить вимозі: очікує інше значення, інший текст, інший стан, іншу роль,
   ніж написано в блоці. "reason" — у чому розбіжність: «кейс очікує X, вимога каже Y».

ЖОРСТКІ ПРАВИЛА:
- Використовуй ЛИШЕ id кейсів із наданого списку. Не придумуй id.
- blockId у відповіді — рівно той, що в запиті.
- Якщо не впевнений — не додавай запис. Хибна тривога дорожча за пропущену.

${CASE_AUTHORING_RULES}

ФОРМАТ ВІДПОВІДІ. Поверни ЛИШЕ валідний JSON:
{
  "gaps": [ { "blockId": "...", "fragment": "...", "suggestion": { "title": "...", "kind": "...", "priority": "...", "preconditions": "...", "checks": ["..."], "tags": ["..."] } } ],
  "duplicates": [ { "caseIds": ["...", "..."], "reason": "..." } ],
  "untestable": [ { "caseId": "...", "reason": "..." } ],
  "contradictions": [ { "caseId": "...", "blockId": "...", "reason": "..." } ]
}
Мова пояснень: ${opts.language}.`;
}

/** Юзер-промпт скіла перевірки покриття: один блок + кейси. */
export function buildValidateCoverageUserPrompt(input: {
  sectionPath: string;
  block: { id: string; heading: string; text: string };
  cases: Array<{ id: string; title: string; checks: string[]; kind: string }>;
}): string {
  return `${JSON.stringify(
    {
      розділ: input.sectionPath,
      блок: { id: input.block.id, заголовок: input.block.heading, текст: input.block.text },
      наявні_кейси: input.cases,
    },
    null,
    2,
  )}

Проаналізуй покриття саме цього блоку.`;
}
